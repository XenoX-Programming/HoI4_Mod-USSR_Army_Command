#!/usr/bin/env python3
"""Generate USSR Army Command mod files from research/roster.json (repo-external)."""
import json, os, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
MOD=ROOT/'USSR_Army_Command'
ROSTER=Path(os.environ.get('USAC_ROSTER',str(ROOT/'tools/data/roster.json')))
R=json.loads(ROSTER.read_text())
PREFIX='USAC_'
def cid(x): return PREFIX+x['slug']
def gfx(x): return 'GFX_'+cid(x)
# characters
lines=['# Generated by tools/build_mod.py. Characters are NOT recruited here; the startup event recruits them only on acceptance.','characters = {']
for x in R:
    lines.append(f'\t{cid(x)} = {{')
    lines.append(f'\t\tname = {cid(x)}')
    lines.append('\t\tportraits = {')
    lines.append(f'\t\t\t{ "army" if x["branch"]=="army" else "navy" } = {{')
    lines.append(f'\t\t\t\tlarge = {gfx(x)}')
    lines.append(f'\t\t\t\tsmall = {gfx(x)}_small')
    lines.append('\t\t\t}')
    lines.append('\t\t}')
    role=x['role']
    lines.append(f'\t\t{role} = {{')
    lines.append(f'\t\t\ttraits = {{ {" ".join(x["traits"])} }}')
    lines.append(f'\t\t\tskill = {x["skill"]}')
    lines.append(f'\t\t\tattack_skill = {x["attack"]}')
    lines.append(f'\t\t\tdefense_skill = {x["defense"]}')
    if x['branch']=='army':
        lines.append(f'\t\t\tplanning_skill = {x["planning"]}')
        lines.append(f'\t\t\tlogistics_skill = {x["logistics"]}')
    else:
        lines.append(f'\t\t\tmaneuvering_skill = {x["maneuvering"]}')
        lines.append(f'\t\t\tcoordination_skill = {x["coordination"]}')
    lines.append('\t\t}')
    lines.append('\t}')
lines.append('}')
(MOD/'common/characters/USAC_soviet_commanders.txt').write_text('\n'.join(lines)+'\n')
# on_actions
ids=' '.join(cid(x) for x in R)
on=f'''# Generated. Fires only for a human-controlled Soviet Union at game start.
on_actions = {{
\ton_startup = {{
\t\teffect = {{
\t\t\tevery_country = {{
\t\t\t\tlimit = {{
\t\t\t\t\ttag = SOV
\t\t\t\t\tis_ai = no
\t\t\t\t}}
\t\t\t\tcountry_event = {{ id = usac_recruit.1 hours = 6 }}
\t\t\t}}
\t\t}}
\t}}
}}
'''
(MOD/'common/on_actions/USAC_on_actions.txt').write_text(on)
# event
accept='\n'.join(f'\t\t\t\trecruit_character = {cid(x)}' for x in R)
ev=f'''namespace = usac_recruit

# Decline is the FIRST option so an unanswered timeout never recruits anyone.
country_event = {{
\tid = usac_recruit.1
\ttitle = usac_recruit.1.t
\tdesc = usac_recruit.1.d
\tpicture = GFX_report_event_soviet_tank_parade
\tis_triggered_only = yes
\tfire_only_once = yes
\ttimeout_days = 30

\toption = {{
\t\tname = usac_recruit.1.a
\t\tai_chance = {{ base = 0 }}
\t}}
\toption = {{
\t\tname = usac_recruit.1.b
\t\tai_chance = {{ base = 100 }}
{accept}
\t}}
}}
'''
(MOD/'events/USAC_recruitment.txt').write_text(ev)
# interface
g=['spriteTypes = {']
for x in R:
    g.append(f'\tspriteType = {{ name = "{gfx(x)}" texturefile = "gfx/leaders/SOV/{x["slug"]}.dds" }}')
    g.append(f'\tspriteType = {{ name = "{gfx(x)}_small" texturefile = "gfx/leaders/SOV/{x["slug"]}_small.dds" }}')
g.append('}')
(MOD/'interface/USAC_portraits.gfx').write_text('\n'.join(g)+'\n')
# localisation
loc=['l_english:']
for x in R:
    loc.append(f' {cid(x)}:0 "{x["name"]}"')
loc += [
 ' usac_recruit.1.t:0 "The Missing Commanders"',
 ' usac_recruit.1.d:0 "A review of the officer corps has identified a group of capable Soviet commanders who are not currently assigned to field commands. Many are still junior officers or staff officers in 1936, but their later careers suggest great potential.\\n\\nDo you wish to bring them into the active command pool now? This is a gameplay choice: accepting recruits them immediately, regardless of their historical 1936 rank. Declining leaves the vanilla roster unchanged."',
 ' usac_recruit.1.a:0 "Not now. Keep the current roster."',
 ' usac_recruit.1.b:0 "Recruit the missing commanders."',
]
(MOD/'localisation/english/USAC_l_english.yml').write_text('\ufeff'+'\n'.join(loc)+'\n')
# descriptors
desc='''name = "USSR Army Command"
version = "1.0.0"
supported_version = "1.19.*"
tags = { "Historical" "Events" "Characters" }
'''
(MOD/'descriptor.mod').write_text(desc)
(ROOT/'USSR_Army_Command.mod').write_text(desc+'path = "mod/USSR_Army_Command"\n')
# docs roster
md=['# Roster and historical notes','', 'All 32 commanders were living in 1936 and reached general/flag rank by 1950. Stats and traits are gameplay abstractions, not historical measurements. Biographies distinguish the 1936 situation from later commands.','', '| Commander | Branch / role | 1936 and later career | Source |','|---|---|---|---|']
for x in R:
    md.append(f'| {x["name"]} ({x["ru"]}) | {x["branch"]} / {x["role"]} | {x["bio"]} | [source]({x["source"]}) |')
(ROOT/'docs/roster.md').write_text('\n'.join(md)+'\n')
print('generated',len(R),'commanders')
